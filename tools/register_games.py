"""Rewrites app/lib/games/game_registry.dart from the game folders.

Each folder `lib/games/<id>/<id>.dart` must define a `<Pascal>Game` class.
Order = section 7 of the spec.
"""
import pathlib

ORDER = [
    "minigolf", "penalty", "freekick", "basket", "bowling", "petanque", "tennis",
    "airhockey", "curling", "archery", "ski", "billard", "darts", "stack",
    "fishing", "parking", "survival", "flappy", "runner", "snake", "racing",
    "motflash", "memory", "calcul",
]
GAMES = pathlib.Path(__file__).resolve().parent.parent / "app" / "lib" / "games"


def pascal(s):
    return "".join(p.capitalize() for p in s.split("_"))


def main():
    ids = [g for g in ORDER if (GAMES / g / f"{g}.dart").exists()]
    imports = sorted([f"import '{g}/{g}.dart';" for g in ids] + ["import 'common/mini_game_definition.dart';"])
    body = "\n".join(f"    {pascal(g)}Game()," for g in ids)
    (GAMES / "game_registry.dart").write_text(
        "\n".join(imports)
        + f"""

/// All mini-games, in catalog order (section 7). Generated by
/// `tools/register_games.py`: adding a game = create its folder + run it.
abstract final class GameRegistry {{
  static const List<MiniGameDefinition> all = [
{body}
  ];

  static MiniGameDefinition? byId(String id) {{
    for (final g in all) {{
      if (g.id == id) return g;
    }}
    return null;
  }}
}}
"""
    )
    print(f"registered {len(ids)} games")


if __name__ == "__main__":
    main()
