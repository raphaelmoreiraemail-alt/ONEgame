/// All mini-games, in catalog order (section 7). Generated by
/// `tools/register_games.py`: adding a game = create its folder + run it.
abstract final class GameRegistry {
  static const List<MiniGameDefinition> all = [
    MinigolfGame(),
    PenaltyGame(),
    FreekickGame(),
    BasketGame(),
    BowlingGame(),
    PetanqueGame(),
    TennisGame(),
    AirhockeyGame(),
    CurlingGame(),
    ArcheryGame(),
    SkiGame(),
    BillardGame(),
    DartsGame(),
    StackGame(),
    FishingGame(),
    ParkingGame(),
    SurvivalGame(),
    FlappyGame(),
    RunnerGame(),
    SnakeGame(),
    RacingGame(),
    MemoryGame(),
    CalculGame(),
  ];

  static MiniGameDefinition? byId(String id) {
    for (final g in all) {
      if (g.id == id) return g;
    }
    return null;
  }
}
